import { join } from 'node:path';
import {
  type HostLaunch,
  type SelfUpdateCli,
  desktopHostLaunch,
  isPathDsh,
  selfUpdateCliFor,
} from './self-update-cli.js';
import {
  CORE_ARTIFACTS,
  SELF_UPDATE_PACKAGES,
  attemptsOf,
  recoveryCommand,
  retryMsOf,
  selfUpdateTiming,
  type SelfUpdatePaths,
  type SelfUpdatePrefetch,
  type SelfUpdateRequest,
} from './self-update-plan.js';

const CMD_QUOTE_SOURCE =
  "const quoteCmdArg = (value) => '\"' + String(value).split('\"').join('\"\"') + '\"';";

const CMD_INSTALL_SOURCE =
  "const runCli = (args) => { const env = { ...process.env, ...CLI.env }; if (!WINDOWS) return spawnSync(CLI.file, args, { env, encoding: 'utf8' }); const line = [CLI.file, ...args].map(quoteCmdArg).join(' '); return spawnSync(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', '\"' + line + '\"'], { env, encoding: 'utf8', windowsVerbatimArguments: true }); };";

export function selfUpdateNodeScript(
  request: SelfUpdateRequest,
  paths: SelfUpdatePaths,
  cli: SelfUpdateCli = selfUpdateCliFor(request.profile),
  platform: NodeJS.Platform = process.platform,
  host: HostLaunch | undefined = desktopHostLaunch(),
  prefetch: SelfUpdatePrefetch | undefined = undefined,
): string {
  const target = request.to === '' ? 'latest' : request.to;
  const restart = isPathDsh(cli) ? '重启一次 dsh' : '退出并重开 Desktop';
  const rescue = recoveryCommand({ profile: request.profile, pkg: request.pkg, version: request.from, cli });
  const last = recoveryCommand({ profile: request.profile, pkg: request.pkg, version: target, cli });
  const missing = isPathDsh(cli)
    ? `PATH 上没有 dsh —— 这一跳没跑。救法：${rescue}`
    : `找不到 Desktop 的 dsh（${cli.file}）—— 这一跳没跑。救法：${rescue}`;
  const fallbackFrom = request.from === '' ? 'from' : request.from;
  const launch = host;
  const waitForHost = launch !== undefined;
  const relaunch = waitForHost && request.relaunch !== false;
  const { waitMs, holdMs, pollMs, hostPid } = selfUpdateTiming(request);
  return [
    '#!/usr/bin/env node',
    "import { spawn, spawnSync } from 'node:child_process';",
    "import { appendFileSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';",
    "import { delimiter, dirname, join } from 'node:path';",
    `const DSH_HOME = ${JSON.stringify(request.dshHome)};`,
    `const PKG = ${JSON.stringify(request.pkg)};`,
    `const PROFILE = ${JSON.stringify(request.profile)};`,
    `const FROM = ${JSON.stringify(request.from)};`,
    `const TO = ${JSON.stringify(target)};`,
    `const WANT = ${JSON.stringify(target)};`,
    `const MARKER = ${JSON.stringify(paths.marker)};`,
    `const LOG = ${JSON.stringify(paths.log)};`,
    `const BACKUP = ${JSON.stringify(join(paths.backup, fallbackFrom))};`,
    `const MANIFEST = join(BACKUP, 'packages.txt');`,
    `const ATTEMPTS = ${String(attemptsOf(request))};`,
    `const RETRY_MS = ${String(retryMsOf(request))};`,
    `const LOCK = ${JSON.stringify(paths.hostLock)};`,
    `const HOST_PID = ${String(hostPid)};`,
    `const WAIT_MS = ${String(waitMs)};`,
    `const HOLD_MS = ${String(holdMs)};`,
    `const POLL_MS = ${String(pollMs)};`,
    `const WAIT_FOR_HOST = ${waitForHost ? 'true' : 'false'};`,
    `const RELAUNCH = ${relaunch ? 'true' : 'false'};`,
    `const LAUNCH = ${JSON.stringify(launch ?? null)};`,
    `const PREFETCH = ${JSON.stringify(prefetch ?? null)};`,
    `const CLI = ${JSON.stringify(cli)};`,
    `const WINDOWS = ${JSON.stringify(platform === 'win32')};`,
    `const MODULES = join(DSH_HOME, 'profiles', PROFILE, 'node_modules');`,
    `const PACKAGES = ${JSON.stringify([...SELF_UPDATE_PACKAGES])};`,
    `const ARTIFACTS = ${JSON.stringify([...CORE_ARTIFACTS])};`,
    CMD_QUOTE_SOURCE,
    CMD_INSTALL_SOURCE,
    "const say = (message) => appendFileSync(LOG, `${new Date().toISOString()} ${message}\\n`);",
    "const versionOf = (name) => { try { const read = JSON.parse(readFileSync(join(MODULES, name, 'package.json'), 'utf8')); return typeof read.version === 'string' ? read.version : ''; } catch { return ''; } };",
    'const onDisk = () => versionOf(PKG);',
    "const writeMarker = (state, version, reason) => writeFileSync(MARKER, JSON.stringify({ pkg: PKG, profile: PROFILE, from: FROM, to: TO, state, version, reason, at: new Date().toISOString() }) + '\\n');",
    "const sleep = (ms) => { if (ms > 0) Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms); };",
    'const hostAlive = () => {',
    '  if (existsSync(LOCK)) return true;',
    '  if (HOST_PID > 0) { try { process.kill(HOST_PID, 0); return true; } catch { return false; } }',
    '  return false;',
    '};',
    'const relaunchHost = () => {',
    '  if (!RELAUNCH || LAUNCH === null) return;',
    '  say(`把 Desktop 拉回来`);',
    "  try { spawn(LAUNCH.file, [...LAUNCH.args], { env: { ...process.env, ...LAUNCH.env }, detached: true, stdio: 'ignore' }).unref(); } catch (error) { say(String(error)); }",
    '};',
    "let lastOut = '';",
    "const occupied = () => /EPERM|EBUSY|operation not permitted/.test(lastOut);",
    'const backed = [];',
    'const backup = () => {',
    '  mkdirSync(BACKUP, { recursive: true });',
    "  writeFileSync(MANIFEST, '');",
    '  for (const name of PACKAGES) {',
    '    const src = join(MODULES, name);',
    "    if (!existsSync(join(src, 'package.json'))) continue;",
    '    const dest = join(BACKUP, name);',
    '    mkdirSync(dirname(dest), { recursive: true });',
    '    rmSync(dest, { recursive: true, force: true });',
    '    cpSync(src, dest, { recursive: true });',
    '    backed.push(name);',
    "    appendFileSync(MANIFEST, name + '\\n');",
    '  }',
    '};',
    'const restore = () => {',
    '  if (backed.length === 0) return false;',
    '  for (const name of backed) {',
    '    const src = join(BACKUP, name);',
    '    if (!existsSync(src)) return false;',
    '    const dest = join(MODULES, name);',
    '    rmSync(dest, { recursive: true, force: true });',
    '    mkdirSync(dirname(dest), { recursive: true });',
    '    cpSync(src, dest, { recursive: true });',
    '  }',
    '  return true;',
    '};',
    'const verify = (want) => {',
    "  if (onDisk() === '') return false;",
    '  for (const name of backed) {',
    '    const version = versionOf(name);',
    "    if (version === '') return false;",
    "    if (want === 'latest') { if (version === FROM) return false; } else if (version !== want) return false;",
    '  }',
    '  for (const artifact of ARTIFACTS) {',
    '    if (!existsSync(join(MODULES, PKG, artifact))) return false;',
    '  }',
    '  return true;',
    '};',
    "const install = (version) => { const result = runCli([...CLI.args, 'plugin', '--profile', PROFILE, 'add', `${PKG}@${version}`]); lastOut = `${result.stdout ?? ''}\\n${result.stderr ?? ''}${result.error ? String(result.error) : ''}`; say(lastOut.trim()); return result.status === 0; };",
    "const canRun = () => { if (CLI.file.includes('/') || (CLI.file.length > 2 && CLI.file[1] === ':')) return existsSync(CLI.file); const exts = WINDOWS ? (process.env.PATHEXT ?? '.EXE;.CMD;.BAT').split(';') : ['']; return (process.env.PATH ?? '').split(delimiter).some((dir) => exts.some((ext) => existsSync(join(dir, CLI.file + ext)))); };",
    "if (!canRun()) { say(" + JSON.stringify(missing) + "); writeMarker('failed', FROM, 'occupied'); process.exit(1); }",
    'say(`开始 ${FROM} -> ${TO}（不卸任何一行，先备份）`);',
    "writeMarker('running', FROM, '');",
    'if (PREFETCH !== null) {',
    "  say('先把包下到 store（还不碰 node_modules）');",
    "  const fetched = spawnSync(PREFETCH.file, [...PREFETCH.args], { env: { ...process.env, ...PREFETCH.env }, encoding: 'utf8' });",
    "  say(fetched.status === 0 ? '预取好了 —— 退出后的那一跳就是本地活了' : '预取没成（不影响换包，只是退出后那一跳会慢一点）');",
    '}',
    'if (WAIT_FOR_HOST) {',
    "  writeMarker('queued', FROM, '');",
    '  let elapsed = 0;',
    '  while (hostAlive()) {',
    '    if (elapsed >= WAIT_MS) { say(`宿主还没退（等了 ${elapsed}ms）—— 这次一个字都不动，留着排队`); process.exit(0); }',
    '    sleep(POLL_MS);',
    '    elapsed += POLL_MS;',
    '  }',
    '  let quiet = 0;',
    '  while (quiet < HOLD_MS) {',
    '    sleep(POLL_MS);',
    "    if (hostAlive()) { say('宿主又回来了 —— 不换，留着排队'); process.exit(0); }",
    '    quiet += POLL_MS;',
    '  }',
    '  say(`宿主已经退了（安静了 ${quiet}ms）—— 开始换`);',
    "  writeMarker('running', FROM, '');",
    '}',
    'backup();',
    'let ok = false;',
    'for (let attempt = 1; attempt <= ATTEMPTS; attempt += 1) {',
    '  if (install(TO) && verify(WANT)) { ok = true; break; }',
    '  if (occupied()) say(`第 ${attempt} 次撞上目录被占用（Windows 上通常是 Desktop 还开着）`);',
    '  say(`第 ${attempt} 次没成（盘上 ${onDisk()}）`);',
    '  if (attempt < ATTEMPTS) sleep(RETRY_MS);',
    '}',
    'if (ok) {',
    '  say(`换好了：${onDisk()} 在盘上（目标 ${TO}），' + restart + ' 才用得上`);',
    "  writeMarker('ok', onDisk(), '');",
    '  relaunchHost();',
    '  process.exit(0);',
    '}',
    "const reason = occupied() || onDisk() === '' ? 'occupied' : 'incomplete';",
    'say(`换版没成（盘上 ${onDisk()}）—— 用本地备份把 ${FROM} 放回去`);',
    'if (restore() && verify(FROM)) {',
    '  say(`已还原：${FROM} 还在盘上（走的是本地备份，没联网），工作台这一行没被动过`);',
    "  writeMarker('restored', FROM, reason);",
    '  process.exit(0);',
    '}',
    'say(`本地还原也没成 —— 退回联网把 ${FROM} 装回去`);',
    'if (install(FROM) && verify(FROM)) {',
    '  say(`已回滚：${FROM} 还在盘上，工作台这一行没被动过`);',
    "  writeMarker('rolled-back', FROM, reason);",
    '  process.exit(0);',
    '}',
    `say(${JSON.stringify(`回滚也没成。救法：${rescue}（或 ${last}）`)});`,
    "writeMarker('failed', onDisk(), 'rollback-failed');",
    'process.exit(1);',
    '',
  ].join('\n');
}
